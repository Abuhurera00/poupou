// Island views. Each one is a small DOM tree built once, with a `sync()` that
// brings it up to date with the state.

import { h, svg, clear, dot } from "./dom";
import { ICONS } from "./icons";
import { Ticker } from "./ticker";
import { Bridge } from "../core/bridge";
import { CLAUDE_ID, State, type AgentTask } from "../core/state";
import { washRGBA, type IslandViewName, type Wash } from "../core/layout";
import { buildPrompt } from "./chat";
import { buildChoose, buildUpload, buildUploading } from "./upload";

export interface ViewActions {
  setView(v: IslandViewName): void;
  collapse(): void;
  setFocus(id: string): void;
  openTerminal(): void;
  /** The ↗ button: opens whatever the focused pill points at. */
  openTarget(): void;
  openUrl(url: string): void;
  decide(d: "allow" | "deny"): void;
  toggleSound(): void;
  setVolume(v: number): void;
  setAutoClose(seconds: number): void;
  openSettingsWindow(): void;
  blip(): void;
  /** Ends the app — the tray icon is easy to lose in the overflow menu. */
  quit(): void;
}

export interface ViewHost {
  el: HTMLElement;
  sync(): void;
  /** Called when the view becomes active, for views with a text field. */
  focus?(): void;
  /** Called every frame while the view is on screen. */
  tick?(nowMs: number): void;
}

// ── Shared pieces ─────────────────────────────────────────────────────────────

function card(wash: Wash, ...children: (Node | string)[]): HTMLElement {
  const el = h("div", { class: wash ? "card wash" : "card" }, ...children);
  if (wash) el.style.setProperty("--wash", washRGBA(wash));
  return el;
}

function btn(
  label: string,
  kind: "primary" | "secondary",
  onClick: () => void,
  kbd?: string,
): HTMLElement {
  return h(
    "button",
    { class: `btn ${kind}`, onclick: onClick },
    h("span", { text: label }),
    kbd ? h("span", { class: "kbd", text: kbd }) : null,
  );
}

/** AgentWho — coloured dot + task name + grey label. */
function agentWho(task: AgentTask | null, label: string): HTMLElement {
  const row = h("div", { class: "who-row" });
  if (task) {
    row.append(dot(task.color, 8), h("span", { class: "n", text: task.name }));
  }
  row.append(h("span", { text: label }));
  return row;
}

function stack(padLeft: number, padRight: number, ...children: Node[]): HTMLElement {
  const el = h("div", { class: "stack" }, ...children);
  el.style.padding = `4px ${padRight}px 4px ${padLeft}px`;
  return el;
}

// ── Header ────────────────────────────────────────────────────────────────────

export function buildHeader(actions: ViewActions): ViewHost {
  const tabHome = h("button", { class: "tab", title: "Overview", onclick: () => go("overview") }, svg(ICONS.house, 13));
  const tabChat = h("button", { class: "tab", title: "Ask", onclick: () => go("prompt") }, svg(ICONS.bubble, 13));
  const tabDrop = h("button", { class: "tab", title: "Drop", onclick: () => go("upload") }, svg(ICONS.plus, 13));

  const gearBtn = h("button", { title: "Settings", onclick: () => go("settings") }, svg(ICONS.gear, 14));
  const soundBtn = h("button", { title: "Mute", onclick: () => actions.toggleSound() }, svg(ICONS.speakerOn, 14));
  const quitBtn = h("button", { class: "quit", title: "Quit Poupou", onclick: () => actions.quit() }, svg(ICONS.power, 13));

  function go(v: IslandViewName) {
    actions.blip();
    actions.setView(v);
  }

  const el = h(
    "div",
    { id: "header" },
    h("div", { class: "tabs" }, tabHome, tabChat, tabDrop),
    h("div", { class: "header-actions" }, gearBtn, soundBtn, quitBtn),
  );

  return {
    el,
    sync() {
      const v = State.view;
      tabHome.classList.toggle("on", v === "overview" || v === "empty");
      tabChat.classList.toggle("on", v === "prompt");
      tabDrop.classList.toggle("on", v === "upload");
      gearBtn.classList.toggle("on", v === "settings");
      clear(gearBtn);
      gearBtn.append(svg(v === "settings" ? ICONS.gearFill : ICONS.gear, 14));
      clear(soundBtn);
      soundBtn.append(svg(State.settings.soundEnabled ? ICONS.speakerOn : ICONS.speakerOff, 14));
      el.style.opacity = v === "confused" ? "0" : "1";
    },
  };
}

// ── Overview ──────────────────────────────────────────────────────────────────

/** What the left card shows while no Claude Code session is running. */
function idleCard(task: AgentTask, actions: ViewActions): HTMLElement {
  const hooked = State.settings.hooksInstalled;
  const links = h("div", { class: "int-actions" },
    h("button", {
      class: "link-btn",
      style: `color:${task.color}b3`,
      text: "Open Visual Studio Code",
      onclick: () => void Bridge.openInVSCode(task.sessionCwd ?? null),
    }),
  );
  if (!hooked) {
    links.append(
      h("button", {
        class: "link-btn",
        style: "color:#8e939c",
        text: "Settings…",
        onclick: () => actions.openSettingsWindow(),
      }),
    );
  }
  return h(
    "div",
    { class: "int-card" },
    h("div", { class: "int-head" }, dot(task.color, 7), h("b", { text: "VS Code" }), h("span", { text: "Claude Code" })),
    h(
      "div",
      { class: "int-status" },
      dot(hooked ? "#22C55E" : "#F4505E", 5),
      h("span", { text: hooked ? "Connected · waiting for a session" : "Hooks not installed" }),
    ),
    links,
  );
}

/** A shortcut in the right-hand card. */
function actionPill(label: string, icon: string, color: string, onClick: () => void): HTMLElement {
  const glyph = h("span", { class: "pill-icon" }, svg(icon, 11));
  glyph.style.color = color;
  const lbl = h("span", { class: "lbl", text: label });
  const pill = h("div", { class: "pill", onclick: onClick }, glyph, lbl);
  pill.style.borderColor = `${color}24`;
  pill.addEventListener("mouseenter", () => {
    pill.style.background = `${color}2e`;
    pill.style.borderColor = `${color}8c`;
    pill.style.boxShadow = `0 2px 10px ${color}59`;
    lbl.style.color = lighten(color, 0.3);
  });
  pill.addEventListener("mouseleave", () => {
    pill.style.background = "";
    pill.style.borderColor = `${color}24`;
    pill.style.boxShadow = "";
    lbl.style.color = "";
  });
  return pill;
}

function buildOverview(actions: ViewActions): ViewHost {
  const ticker = new Ticker();
  const who = h("div", { class: "who" });
  const tickerBody = h("div", { class: "card-body" }, who, ticker.el);
  const leftBody = h("div", { class: "left-body" });
  const jump = h(
    "button",
    { class: "icon-btn jump", title: "Open", onclick: () => actions.openTarget() },
    svg(ICONS.arrowUpRight, 8),
  );
  const left = card(null, leftBody, jump);

  const go = (v: IslandViewName) => {
    actions.blip();
    actions.setView(v);
  };
  const pills = h(
    "div",
    { class: "pills" },
    actionPill("Ask Claude", ICONS.bubble, "#7C5CFF", () => go("prompt")),
    actionPill("Drop a file", ICONS.plus, "#22C55E", () => go("upload")),
    actionPill("VS Code", ICONS.arrowUpRight, "#38BDF8", () => actions.openTarget()),
    actionPill("Settings", ICONS.gear, "#F29B38", () => actions.openSettingsWindow()),
  );
  const right = card(null, pills);

  const el = h("div", { class: "view overview" },
    h("div", { class: "left" }, left),
    h("div", { class: "right" }, right),
  );

  let mode: "ticker" | "card" | null = null;
  let cardKey = "";

  return {
    el,
    tick(nowMs: number) {
      if (mode === "ticker") ticker.tick(nowMs);
    },
    sync() {
      const task = State.focusTask;
      if (!task) return;

      // A live Claude Code session gets the ticker; otherwise the card says
      // whether the hooks are in place.
      const sessionActive =
        task.id === CLAUDE_ID && (task.state !== "idle" || task.steps.length > 0);

      if (sessionActive) {
        if (mode !== "ticker") {
          clear(leftBody);
          leftBody.append(tickerBody);
          mode = "ticker";
          cardKey = "";
        }
        clear(who);
        who.append(
          dot(task.color, 7),
          h("span", { class: "name", text: task.name }),
          h("span", { class: "tool", text: "Claude Code" }),
        );
        if (task.steps.length > 1) {
          who.append(h("span", {
            class: "count",
            text: `${Math.min(task.stepIndex + 1, task.steps.length)}/${task.steps.length}`,
          }));
        }
        ticker.sync(task);
      } else {
        const key = `${task.id}~${State.settings.hooksInstalled}~${task.sessionCwd ?? ""}`;
        if (key !== cardKey || mode !== "card") {
          cardKey = key;
          mode = "card";
          clear(leftBody);
          leftBody.append(idleCard(task, actions));
        }
      }
    },
  };
}

function lighten(hex: string, amount: number): string {
  const v = parseInt(hex.replace("#", ""), 16);
  const c = [(v >> 16) & 255, (v >> 8) & 255, v & 255].map((x) =>
    Math.min(255, Math.round(x + amount * 255)),
  );
  return `rgb(${c[0]},${c[1]},${c[2]})`;
}

